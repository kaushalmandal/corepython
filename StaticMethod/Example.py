class Test:
    @staticmethod
    def add(x,y):
        print('The sum is :',x+y)
    @staticmethod
    def product(x,y):
        print('The products is :',x*y)
    @staticmethod
    def average(x,y):
        print('The average is :',(x+y)//2)

Test.add(10,20)
Test.product(10,20)
Test.average(10,20)
